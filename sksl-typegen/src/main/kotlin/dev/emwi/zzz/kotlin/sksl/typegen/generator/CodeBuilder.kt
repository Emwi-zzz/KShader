package dev.emwi.zzz.kotlin.sksl.typegen.generator

class CodeBuilder(private val indentStr: String = "    ") {
    private val sb = StringBuilder()
    private var indentLevel = 0

    fun indent() {
        indentLevel++
    }

    fun unindent() {
        if (indentLevel > 0) indentLevel--
    }

    fun line(str: String = "") {
        if (str.isEmpty()) {
            sb.append("\n")
        } else {
            sb.append(indentStr.repeat(indentLevel)).append(str).append("\n")
        }
    }

    fun block(header: String, body: () -> Unit) {
        line("$header {")
        indent()
        body()
        unindent()
        line("}")
    }

    override fun toString(): String = sb.toString()
}

fun buildFile(packageName: String, imports: List<String> = emptyList(), content: CodeBuilder.() -> Unit): String {
    val b = CodeBuilder()
    b.line("// Generated by :sksl-typegen. Do not modify manually.")
    b.line("@file:Suppress(\"unused\", \"UNUSED_PARAMETER\", \"ClassName\", \"PropertyName\", \"MemberVisibilityCanBePrivate\", \"RedundantVisibilityModifier\")")
    b.line("package $packageName")
    b.line()
    if (imports.isNotEmpty()) {
        for (imp in imports.sorted().distinct()) {
            b.line("import $imp")
        }
        b.line()
    }
    b.content()
    return b.toString()
}
